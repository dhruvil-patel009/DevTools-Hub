export function getAllTools(includeInactive = false): ToolDefinition[] {
  return TOOL_REGISTRY.filter((t) => includeInactive || t.isActive).sort(
    (a, b) => a.sortOrder - b.sortOrder
  );
}

export function getFeaturedTools(): ToolDefinition[] {
  return TOOL_REGISTRY.filter((t) => t.isActive && t.isFeatured).sort(
    (a, b) => a.sortOrder - b.sortOrder
  );
}

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOL_REGISTRY.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: CategorySlug): ToolDefinition[] {
  return TOOL_REGISTRY.filter((t) => t.isActive && t.category === category).sort(
    (a, b) => a.sortOrder - b.sortOrder
  );
}

export function searchTools(query: string): ToolDefinition[] {
  const q = query.trim().toLowerCase();
  if (!q) return getAllTools();
  return getAllTools().filter(
    (tool) =>
      tool.name.toLowerCase().includes(q) ||
      tool.description.toLowerCase().includes(q) ||
      tool.category.toLowerCase().includes(q) ||
      tool.keywords.some((kw) => kw.toLowerCase().includes(q))
  );
}

export function getRelatedTools(tool: ToolDefinition): ToolDefinition[] {
  return tool.relatedSlugs
    .map((slug) => getToolBySlug(slug))
    .filter((t): t is ToolDefinition => Boolean(t && t.isActive));
}
